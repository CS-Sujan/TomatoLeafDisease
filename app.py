import numpy as np
import streamlit as st
import tensorflow as tf
from PIL import Image

# ==========================================
# SETTINGS
# ==========================================

MODEL_PATH = "model/tomato_disease_model.keras"
IMAGE_SIZE = (128, 128)

CLASS_NAMES = [
    "Early_Blight",
    "Healthy",
    "Late_Blight",
    "Leaf_Spot"
]

# ==========================================
# PAGE SETTINGS
# ==========================================

st.set_page_config(
    page_title="Tomato Leaf Disease Detection",
    page_icon="🍅",
    layout="centered"
)

# ==========================================
# LOAD MODEL
# ==========================================

@st.cache_resource
def load_model():
    return tf.keras.models.load_model(MODEL_PATH)


model = load_model()

# ==========================================
# TITLE
# ==========================================

st.title("🍅 Tomato Leaf Disease Detection")

st.write(
    "Upload a tomato leaf image to detect the possible disease."
)

st.write(
    "The system uses a CNN model trained on four tomato leaf classes."
)

# ==========================================
# IMAGE UPLOAD
# ==========================================

uploaded_file = st.file_uploader(
    "Choose a tomato leaf image",
    type=["jpg", "jpeg", "png"]
)

# ==========================================
# PROCESS IMAGE
# ==========================================

if uploaded_file is not None:

    # Open uploaded image
    image = Image.open(uploaded_file).convert("RGB")

    # Display uploaded image
    st.subheader("Uploaded Image")

    st.image(
        image,
        caption="Selected Tomato Leaf",
        use_container_width=True
    )

    # ======================================
    # RESIZE IMAGE
    # ======================================

    resized_image = image.resize(IMAGE_SIZE)

    # Convert to NumPy
    image_array = np.array(
        resized_image,
        dtype=np.float32
    )

    # Add batch dimension
    image_array = np.expand_dims(
        image_array,
        axis=0
    )

    # IMPORTANT:
    # DO NOT divide by 255.
    #
    # Your trained model already contains:
    #
    # layers.Rescaling(1./255)
    #
    # So the model performs normalization itself.

    # ======================================
    # PREDICTION
    # ======================================

    predictions = model.predict(
        image_array,
        verbose=0
    )[0]

    predicted_index = np.argmax(predictions)

    predicted_class = CLASS_NAMES[predicted_index]

    confidence = predictions[predicted_index] * 100

    # ======================================
    # RESULT
    # ======================================

    st.subheader("Prediction Result")

    st.success(
        f"Prediction: {predicted_class}"
    )

    st.info(
        f"Confidence: {confidence:.2f}%"
    )

    # ======================================
    # ALL PROBABILITIES
    # ======================================

    st.subheader("Prediction Probabilities")

    for i, class_name in enumerate(CLASS_NAMES):

        probability = float(predictions[i])

        st.write(
            f"**{class_name}**: {probability * 100:.2f}%"
        )

        st.progress(probability)

    # ======================================
    # SIMPLE INTERPRETATION
    # ======================================

    st.subheader("Result Interpretation")

    if predicted_class == "Healthy":

        st.success(
            "The model predicts that the uploaded "
            "tomato leaf is Healthy."
        )

    elif predicted_class == "Early_Blight":

        st.warning(
            "The model predicts possible Early Blight."
        )

    elif predicted_class == "Late_Blight":

        st.warning(
            "The model predicts possible Late Blight."
        )

    elif predicted_class == "Leaf_Spot":

        st.warning(
            "The model predicts possible Leaf Spot."
        )

    st.caption(
        "Note: This prediction is generated by a machine-learning "
        "model and should not be treated as a professional "
        "agricultural diagnosis."
    )